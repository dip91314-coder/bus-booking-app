export function getRandomAvatar(seed = '') {
  if (!seed) {
    return DIVERSE_AVATARS[Math.floor(Math.random() * DIVERSE_AVATARS.length)];
  }
  let hash = 0;
  for (let i = 0; i < seed.length; i++) {
    hash = (hash << 5) - hash + seed.charCodeAt(i);
  }
  return DIVERSE_AVATARS[Math.abs(hash) % DIVERSE_AVATARS.length];
}

export function resolveUserAvatar(user) {
  if (user?.avatar && !user.avatar.includes('photo-1535713875002')) {
    return user.avatar;
  }
  const seed = user?.email || user?.name || user?._id || user?.id || 'traveller';
  return getRandomAvatar(seed);
}
